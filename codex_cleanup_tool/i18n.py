def _windows_locale_name() -> str:
    if os.name == "nt":
        buffer = ctypes.create_unicode_buffer(85)
        if ctypes.windll.kernel32.GetUserDefaultLocaleName(buffer, len(buffer)):
            return buffer.value
    value = locale.getlocale()[0]
    return value or "en"


def _windows_ui_language_name() -> str:
    if os.name == "nt":
        language_count = ctypes.c_ulong()
        buffer_size = ctypes.c_ulong()
        get_languages = ctypes.windll.kernel32.GetUserPreferredUILanguages
        get_languages(
            0x00000008,
            ctypes.byref(language_count),
            None,
            ctypes.byref(buffer_size),
        )
        if buffer_size.value:
            buffer = ctypes.create_unicode_buffer(buffer_size.value)
            if get_languages(
                0x00000008,
                ctypes.byref(language_count),
                buffer,
                ctypes.byref(buffer_size),
            ):
                return buffer.value
    return _windows_locale_name()


def detect_system_language() -> str:
    return (
        SIMPLIFIED_CHINESE
        if _windows_ui_language_name().lower().startswith("zh")
        else ENGLISH
    )


def resolve_language(saved_language: object, system_language: str | None = None) -> str:
    if saved_language in SUPPORTED_LANGUAGES:
        return str(saved_language)
    detected = system_language or detect_system_language()
    return detected if detected in SUPPORTED_LANGUAGES else ENGLISH


class Translator:
    def __init__(self, language: str):
        self.language = resolve_language(language, ENGLISH)

    def set_language(self, language: str) -> None:
        self.language = resolve_language(language, ENGLISH)

    def __call__(self, source: object, **values) -> object:
        if not isinstance(source, str):
            return source
        translated = source
        if self.language == ENGLISH:
            translated = ENGLISH_TEXT.get(source, source)
            if translated == source:
                for chinese in sorted(ENGLISH_TEXT, key=len, reverse=True):
                    translated = translated.replace(chinese, ENGLISH_TEXT[chinese])
        return translated.format(**values) if values else translated
